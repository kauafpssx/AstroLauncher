function labelFor(fileName: string): string {
  if (LABEL_OVERRIDES[fileName]) return LABEL_OVERRIDES[fileName]
  return fileName
    .split('_')
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(' ')
}

